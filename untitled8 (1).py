def detect_target_column(df: pd.DataFrame) -> str:
    """Auto-detect the real-world 'total load actual' column regardless of
    whether it uses spaces or underscores in the source file."""
    candidates = [
        c for c in df.columns
        if "total" in c.lower() and "load" in c.lower() and "actual" in c.lower()
    ]
    if not candidates:
        raise KeyError(
            f"Could not locate a 'total load actual' style column. "
            f"Available columns: {df.columns.tolist()}"
        )
    return candidates[0]

CITY_POPULATION_WEIGHTS = {
    "Madrid": 6_700_000,
    "Barcelona": 5_500_000,
    "Valencia": 1_650_000,
    "Seville": 1_300_000,
    "Bilbao": 1_000_000,
}


def build_population_weighted_weather(df_weather: pd.DataFrame) -> pd.DataFrame:
    """Collapse 5-city weather data into a single population-weighted
    national signal per timestamp, instead of a naive city-average."""
    df_weather = df_weather.copy()
    df_weather["city_name"] = df_weather["city_name"].str.strip()

    unknown_cities = set(df_weather["city_name"].unique()) - set(CITY_POPULATION_WEIGHTS)
    if unknown_cities:
        logger.warning(f"Unweighted / unknown cities found, dropping: {unknown_cities}")
        df_weather = df_weather[df_weather["city_name"].isin(CITY_POPULATION_WEIGHTS)]

    df_weather["weight"] = df_weather["city_name"].map(CITY_POPULATION_WEIGHTS)

    def weighted_avg(group: pd.DataFrame, col: str) -> float:
        return np.average(group[col], weights=group["weight"])

    records = []
    for dt, group in df_weather.groupby("dt_iso"):
        records.append({
            "dt_iso": dt,
            "temp": weighted_avg(group, "temp"),
            "humidity": weighted_avg(group, "humidity"),
            "wind_speed": weighted_avg(group, "wind_speed"),
        })
    df_agg = pd.DataFrame(records)
    logger.info(f"Population-weighted weather aggregated -> {df_agg.shape[0]} timestamps.")
    return df_agg

def add_fourier_terms(df: pd.DataFrame, period: int, order: int, prefix: str) -> pd.DataFrame:
    """Generic Fourier-term generator. `order` harmonics capture richer
    seasonal shape than a single sin/cos pair (e.g. double-peak daily
    industrial demand curves)."""
    t = np.arange(len(df))
    for k in range(1, order + 1):
        df[f"{prefix}_sin_{k}"] = np.sin(2 * np.pi * k * t / period)
        df[f"{prefix}_cos_{k}"] = np.cos(2 * np.pi * k * t / period)
    return df


def load_and_engineer_data(energy_path: str, weather_path: str):
    print("🧹 Parsing and aligning multi-city industrial data vectors...")

    df_energy = load_csv_safely(energy_path, required_cols=["time"])
    df_weather = load_csv_safely(
        weather_path, required_cols=["dt_iso", "city_name", "temp", "humidity", "wind_speed"]
    )

    # --- Time-zone alignment: Spain's TSO data is timezone-aware; normalize
    # everything to UTC to avoid silent misalignment across DST transitions ---
    df_energy["time"] = pd.to_datetime(df_energy["time"], utc=True)
    df_weather["dt_iso"] = pd.to_datetime(df_weather["dt_iso"], utc=True)

    df_weather_clean = build_population_weighted_weather(df_weather)

    df = pd.merge(df_energy, df_weather_clean, left_on="time", right_on="dt_iso", how="inner")
    dropped_pct = (1 - len(df) / len(df_energy)) * 100
    if dropped_pct > 0:
        logger.warning(f"{dropped_pct:.2f}% of energy rows dropped on weather merge.")

    df = df.set_index("time").sort_index()

    target_col = detect_target_column(df)
    print(f"✅ Detected target column: '{target_col}'")
    df[target_col] = df[target_col].ffill()

    # --- Keep the TSO's own official day-ahead forecast as a benchmark
    # column: this lets us later ask "did our model beat the grid operator's
    # own forecast?" instead of only benchmarking against a naive baseline ---
    if "total load forecast" in df.columns:
        df["tso_forecast_benchmark"] = df["total load forecast"]

    # Scale temperature metric to Celsius if required
    df["temp_c"] = df["temp"] - 273.15 if df["temp"].mean() > 200 else df["temp"]

    # Industrial Degree Days
    df["CDD"] = np.maximum(0, df["temp_c"] - 22.0)
    df["HDD"] = np.maximum(0, 18.0 - df["temp_c"])

    # Calendar-cyclic signals (kept for LightGBM interpretability via SHAP)
    df["hour"] = df.index.hour
    df["day_of_week"] = df.index.dayofweek
    df["month"] = df.index.month
    df["hour_sin"] = np.sin(2 * np.pi * df["hour"] / 24.0)
    df["hour_cos"] = np.cos(2 * np.pi * df["hour"] / 24.0)
    df["day_sin"] = np.sin(2 * np.pi * df["day_of_week"] / 7.0)
    df["day_cos"] = np.cos(2 * np.pi * df["day_of_week"] / 7.0)

    # Higher-order Fourier terms for annual seasonality (captures summer AC
    # peaks + winter heating peaks better than a single sinusoid)
    df = add_fourier_terms(df, period=365.25 * 24, order=3, prefix="annual")

    # Structural autoregressive lags
    df["load_lag_24"] = df[target_col].shift(24)
    df["load_lag_168"] = df[target_col].shift(168)
    df["load_rolling_mean_24"] = df[target_col].shift(1).rolling(window=24).mean()
    df["load_rolling_std_24"] = df[target_col].shift(1).rolling(window=24).std()

    return df.dropna(), target_col

