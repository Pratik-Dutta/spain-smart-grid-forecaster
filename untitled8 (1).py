def parse_datetime_column(df: pd.DataFrame, col: str, utc: bool = True) -> pd.DataFrame:
    """Convert a column to datetime, coercing bad values to NaT and reporting them."""
    before_na = df[col].isna().sum()
    df[col] = pd.to_datetime(df[col], utc=utc, errors="coerce")
    after_na = df[col].isna().sum()

    dropped = after_na - before_na
    if dropped > 0:
        logger.warning(f"{dropped} unparseable timestamps in '{col}' converted to NaT.")

    return df


def optimize_dtypes(df: pd.DataFrame) -> pd.DataFrame:
    """Downcast numeric columns to save memory — useful for large weather/energy datasets."""
    float_cols = df.select_dtypes(include=["float64"]).columns
    int_cols = df.select_dtypes(include=["int64"]).columns

    df[float_cols] = df[float_cols].apply(pd.to_numeric, downcast="float")
    df[int_cols] = df[int_cols].apply(pd.to_numeric, downcast="integer")

    return df


def build_weather_aggregate(
    df_weather: pd.DataFrame,
    dt_col: str = "dt_iso",
    agg_map: Optional[dict] = None,
) -> pd.DataFrame:
    """
    Aggregate multi-city weather data into a single national signal per timestamp.
    Defaults to mean, but agg_map lets you customize per-column logic
    (e.g. max wind_speed for grid-risk modeling instead of mean).
    """
    agg_map = agg_map or {"temp": "mean", "humidity": "mean", "wind_speed": "mean"}

    missing = set(agg_map.keys()) - set(df_weather.columns)
    if missing:
        raise KeyError(f"Weather aggregation columns missing from data: {missing}")

    df_agg = df_weather.groupby(dt_col).agg(agg_map).reset_index()
    logger.info(f"Aggregated weather data → {df_agg.shape[0]} unique timestamps.")
    return df_agg


def merge_energy_weather(
    df_energy: pd.DataFrame,
    df_weather_clean: pd.DataFrame,
    energy_time_col: str = "time",
    weather_time_col: str = "dt_iso",
) -> pd.DataFrame:
    """Merge energy and weather data with pre/post row-count diagnostics."""
    pre_rows = len(df_energy)

    df = pd.merge(
        df_energy,
        df_weather_clean,
        left_on=energy_time_col,
        right_on=weather_time_col,
        how="inner",
    )

    post_rows = len(df)
    dropped_pct = (1 - post_rows / pre_rows) * 100 if pre_rows else 0

    logger.info(f"Merged dataset shape: {df.shape}")
    if dropped_pct > 0:
        logger.warning(
            f"{dropped_pct:.2f}% of energy rows had no matching weather timestamp and were dropped."
        )

    return df



