class SmartGridMetaLearner:
    """
    Blends Tabular Machine Learning (LightGBM) with Time-Series LLMs
    (Chronos) using an optimized Ridge Meta-Learner model.
    """
    def __init__(self):
        # Constrain to positive alpha weights to prevent inverse tracking anomalies
        self.meta_model = Ridge(alpha=1.0, positive=True, fit_intercept=False)

    def train_meta_learner(self, calibration_df, target_col):
        """
        Learns the operational strengths of both models from validation data.
        """
        print("🔗 Training Stacking Meta-Learner on base model residual vectors...")
        # Extract individual model prediction fields
        X_calib = calibration_df[['lgb_pred', 'chronos_pred']].values
        y_calib = calibration_df[target_col].values

        self.meta_model.fit(X_calib, y_calib)

        # Save learned weight coefficients
        self.lgb_weight = self.meta_model.coef_[0]
        self.chronos_weight = self.meta_model.coef_[1]

        print(f"📊 Learned Blending Architecture Weights -> LightGBM: {self.lgb_weight:.3f} | Chronos: {self.chronos_weight:.3f}")

    def predict_hybrid(self, inference_df):
        """Generates the optimal stacked prediction vector."""
        X_inf = inference_df[['lgb_pred', 'chronos_pred']].values
        return self.meta_model.predict(X_inf)

